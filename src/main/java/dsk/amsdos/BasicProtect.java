    /** XOR auto-inverse : cette même méthode chiffre ou déchiffre le payload (header AMSDOS déjà retiré). */
    public static byte[] decode(byte[] payload) {
        byte[] out = new byte[payload.length];
        for (int i = 0; i < payload.length; i++) {
            out[i] = (byte) (payload[i] ^ KEY[i % KEY.length]);
        }
        return out;
    }
